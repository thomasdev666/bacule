        /// <summary>
        /// Typographie française, appliquée une fois à tous les textes français : espace insécable avant « ! ? : ; » et
        /// « % », et à l'intérieur des guillemets. Un texte qui passe à la ligne ne laisse donc jamais un « ! » ou un
        /// « : » tout seul au début de la ligne suivante.
        /// </summary>
        static Loc()
        {
            foreach (var row in Table.Values) row[0] = FrenchTypography(row[0]);
        }

        public static string FrenchTypography(string s)
        {
            if (string.IsNullOrEmpty(s) || s.IndexOf(' ') < 0) return s;
            var sb = new System.Text.StringBuilder(s.Length);
            for (int i = 0; i < s.Length; i++)
            {
                char c = s[i];
                if (c == ' ')
                {
                    char next = i + 1 < s.Length ? s[i + 1] : '\0';
                    char prev = i > 0 ? s[i - 1] : '\0';
                    // « ?! » compte comme un seul signe ; un espace suivi d'un autre espace reste un espace normal.
                    bool before = next == '!' || next == '?' || next == ';' || next == '%' || next == '»'
                        || (next == ':' && (i + 2 >= s.Length || s[i + 2] == ' ' || s[i + 2] == '\n'));
                    if (before || prev == '«') c = '\u00A0';
                }
                sb.Append(c);
            }
            return sb.ToString();
        }

        public static string Get(string key)
        {
            if (!Table.TryGetValue(key, out var row)) return key;
            int i = Language == "en" ? 1 : 0;
            return row[i];
        }

        public static string Format(string key, params object[] args) => string.Format(Get(key), args);

        /// <summary>Le jeu est publié en français uniquement (décision du porteur de projet) ; l'anglais reste écrit pour plus tard.</summary>
        public static bool FrenchOnly = true;

        public static string Resolve(string preferred, string systemLanguage)
        {
            if (FrenchOnly) return "fr";
            if (preferred == "fr" || preferred == "en") return preferred;
            return systemLanguage == "French" || systemLanguage == "fr" ? "fr" : (string.IsNullOrEmpty(systemLanguage) ? "fr" : "en");
        }

